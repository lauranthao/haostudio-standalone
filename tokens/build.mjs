// HAo Studio design tokens — Style Dictionary 4.x build (build-29 adoption).
// Run from tokens/:  node build.mjs
// Outputs: lib/generated/hao_tokens.dart (Dart) + ios/Runner/HaoTokens.swift (Swift).
// DTCG source: hao.tokens.json. $value = LIGHT; $extensions.hao.dark = DARK.
//
// VOID (chen 2026-11-22, build-29 adoption): `color.theme.*.tab-pill`
// and `motion.settle-spring.*` are Kumone bottom-bar values. The
// Kumone bar is gone (replaced by the Apple-native GlassTabBar), so
// these tokens are frozen history only — generated, never wired into
// the tab bar or any animation. The tokens test asserts they are NOT
// referenced by lib/widgets/app_shell.dart.
//
// NOTE: Style Dictionary logs a "token collisions" warning because its
// built-in check uses only the LEAF name (all four themes have an
// `accent`, `scaffold`, ...). Our formats name tokens by FULL PATH
// (appleGlassAccent vs darkGoldAccent), so the outputs contain zero
// duplicate identifiers (verified). The warning is a false positive here.
import StyleDictionary from 'style-dictionary';
import { fileURLToPath } from 'node:url';
import path from 'node:path';

const dir = path.dirname(fileURLToPath(import.meta.url));
const appRoot = path.resolve(dir, '..'); // standalone-app-merge23/

const toCamel = (parts) =>
  parts
    .flatMap((p) => p.split('-'))
    .map((w, i) => (i === 0 ? w : w[0].toUpperCase() + w.slice(1)))
    .join('');

// color.theme.apple-glass.accent -> appleGlassAccent ; color.live-red -> liveRed
const colorName = (p) => {
  const parts = [...p];
  parts.shift(); // 'color'
  if (parts[0] === 'theme') parts.shift();
  return toCamel(parts);
};
const otherName = (p) => toCamel(p);

// '#RRGGBB' -> 0xFFRRGGBB ; '#RRGGBBAA' -> 0xAARRGGBB (Dart Color wants AARRGGBB)
const dartHex = (hex) => {
  const h = hex.replace('#', '');
  if (h.length === 6) return `0xFF${h}`;
  if (h.length === 8) return `0x${h.slice(6)}${h.slice(0, 6)}`;
  throw new Error(`bad hex ${hex}`);
};

// '#RRGGBB[AA]' -> UIColor(red:green:blue:alpha:) components
const uiColor = (hex) => {
  const h = hex.replace('#', '');
  const r = (parseInt(h.slice(0, 2), 16) / 255).toFixed(3);
  const g = (parseInt(h.slice(2, 4), 16) / 255).toFixed(3);
  const b = (parseInt(h.slice(4, 6), 16) / 255).toFixed(3);
  const a = h.length === 8 ? (parseInt(h.slice(6, 8), 16) / 255).toFixed(3) : '1.000';
  return `UIColor(red: ${r}, green: ${g}, blue: ${b}, alpha: ${a})`;
};

const isColor = (t) => t.path[0] === 'color';
const darkOf = (t) => t.$extensions?.hao?.dark ?? t.$value;
const valueOf = (t) => t.$value ?? t.value;

const dartFormat = ({ dictionary }) => {
  const lines = [
    '// Generated by Style Dictionary from tokens/hao.tokens.json.',
    '// Do not edit by hand — run `node tokens/build.mjs` instead.',
    '// Light values are the bare names; dark values get a `Dark` suffix.',
    '// VOID (chen 2026-11-22): *TabPill + motionSettleSpring* are Kumone',
    '// bottom-bar values, frozen history only — never wire into the tab bar.',
    '',
    "import 'package:flutter/material.dart';",
    '',
    '/// HAo Studio design tokens (generated).',
    'abstract final class HaoTokens {',
  ];
  for (const t of dictionary.allTokens) {
    if (isColor(t)) {
      const name = colorName(t.path);
      lines.push(`  static const Color ${name} = Color(${dartHex(valueOf(t))});`);
      const dark = darkOf(t);
      if (dark !== valueOf(t)) {
        lines.push(`  static const Color ${name}Dark = Color(${dartHex(dark)});`);
      }
    } else if (t.$type === 'dimension' || t.$type === 'number') {
      const name = otherName(t.path);
      const v = valueOf(t);
      if (typeof v !== 'number') throw new Error(`non-numeric ${t.path.join('.')}: ${v}`);
      // Font weights are ints; everything else doubles.
      const isWeight = t.path.at(-1) === 'weight';
      lines.push(
        isWeight
          ? `  static const int ${name} = ${v};`
          : `  static const double ${name} = ${Number.isInteger(v) ? `${v}.0` : `${v}`};`,
      );
    }
  }
  lines.push('}');
  return lines.join('\n') + '\n';
};

const swiftFormat = ({ dictionary }) => {
  const lines = [
    '// Generated by Style Dictionary from tokens/hao.tokens.json.',
    '// Do not edit by hand — run `node tokens/build.mjs` instead.',
    '// Colors resolve light/dark by trait collection (UIColor dynamic provider).',
    '// VOID (chen 2026-11-22): *TabPill + motionSettleSpring* are Kumone',
    '// bottom-bar values, frozen history only — never wire into the tab bar.',
    '',
    'import UIKit',
    '',
    '/// HAo Studio design tokens (generated).',
    'public enum HaoTokens {',
  ];
  for (const t of dictionary.allTokens) {
    if (isColor(t)) {
      const name = colorName(t.path);
      const light = uiColor(valueOf(t));
      const dark = darkOf(t);
      if (dark !== valueOf(t)) {
        lines.push(
          `  public static let ${name} = UIColor { traits in`,
          `    traits.userInterfaceStyle == .dark ? ${uiColor(dark)} : ${light}`,
          '  }',
        );
      } else {
        lines.push(`  public static let ${name} = ${light}`);
      }
    } else if (t.$type === 'dimension' || t.$type === 'number') {
      const name = otherName(t.path);
      const v = valueOf(t);
      if (typeof v !== 'number') throw new Error(`non-numeric ${t.path.join('.')}: ${v}`);
      lines.push(`  public static let ${name}: CGFloat = ${v}`);
    }
  }
  lines.push('}');
  return lines.join('\n') + '\n';
};

const sd = new StyleDictionary({
  source: [path.join(dir, 'hao.tokens.json')],
  platforms: {
    dart: {
      buildPath: path.join(appRoot, 'lib', 'generated') + path.sep,
      files: [{ destination: 'hao_tokens.dart', format: 'dart/hao-tokens' }],
    },
    swift: {
      // Straight into the Runner target (registered in project.pbxproj).
      buildPath: path.join(appRoot, 'ios', 'Runner') + path.sep,
      files: [{ destination: 'HaoTokens.swift', format: 'swift/hao-tokens' }],
    },
  },
  hooks: {
    formats: {
      'dart/hao-tokens': dartFormat,
      'swift/hao-tokens': swiftFormat,
    },
  },
});

await sd.buildAllPlatforms();
console.log('tokens built: lib/generated/hao_tokens.dart + ios/Runner/HaoTokens.swift');
